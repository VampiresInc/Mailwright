M.languages = {{"auto", "Automatic (WoW language)"}, {"enUS", "English"}, {"deDE", "Deutsch"},
    {"frFR", "Français"}, {"esES", "Español (España)"}, {"esMX", "Español (Latinoamérica)"},
    {"itIT", "Italiano"}, {"ptBR", "Português (Brasil)"}, {"ruRU", "Русский"},
    {"koKR", "한국어"}, {"zhCN", "简体中文"}, {"zhTW", "繁體中文"}}
function M:Locale()
    local choice = self.db and self.db.options.language or "auto"
    if choice ~= "enUS" and choice ~= "enGB" and not translations[choice] then choice = GetLocale and GetLocale() or "enUS" end
    return translations[choice] and choice or "enUS"
end
function M:L(text)
    local t = translations[self:Locale()]
    return t and t[text] or text
end
function M:F(text, ...)
    return string.format(self:L(text), ...)
end
function M:LanguageName()
    for _, entry in ipairs(self.languages) do
        if entry[1] == self.db.options.language then return self:L(entry[2]) end
    end
    return self:L("Automatic (WoW language)")
end
function M:ChooseLanguage(anchor)
    local entries = {}
    for _, entry in ipairs(self.languages) do
        local code, name = entry[1], entry[2]
        entries[#entries + 1] = {text = (code == self.db.options.language and "[x] " or "") .. self:L(name), action = function()
            M.db.options.language = code
            M.menu:Hide()
            if M.settingsPanel then M.settingsPanel.refresh() end
            M:Print(M:L("Reload UI to apply language changes."))
        end}
    end
    local depth = anchor and anchor.GetParent and anchor:GetParent() == self.menu and 2 or 1
    self:SmallMenu(self:L("Language"), entries, anchor, nil, depth)
end

function M:MenuText(text)
    local direct = self:L(text)
    if direct ~= text then return direct end
    local mark, body = text:match("^(%[[x ]%] )(.*)$")
    if mark then return mark .. self:MenuText(body) end
    local heading = text:match("^(.*) >$")
    if heading then return self:L(heading) .. " >" end
    if text == "< Contacts" then return "< " .. self:L("Contacts") end
    for _, prefix in ipairs({"Free bag slots: ", "Delay: "}) do
        if text:sub(1, #prefix) == prefix then return self:L(prefix) .. text:sub(#prefix + 1) end
    end
    return text
end
